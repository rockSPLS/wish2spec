export type PromptFragment = { n: number; path: string; text: string };

function fragmentsBlock(fragments: PromptFragment[]): string {
  if (fragments.length === 0) return "Фрагменты документации: в документах ничего не найдено.";
  return [
    "Фрагменты документации:",
    ...fragments.map((f) => `[${f.n}] ${f.path}\n${f.text}`),
  ].join("\n\n");
}

// Заявку пишет посторонний человек: если в её тексте есть «<<<» или «>>>», он мог бы «закрыть»
// заявку раньше времени и дописать что-то от имени промпта. Такие последовательности заменяются
// похожими кавычками — для модели смысл текста тот же, а границы заявки подделать нельзя
function requestBlock(request: string): string {
  const safe = request.replace(/<{3,}/g, (m) => "‹".repeat(m.length)).replace(/>{3,}/g, (m) => "›".repeat(m.length));
  return `Входящая заявка:\n<<<\n${safe}\n>>>`;
}

export function analysisPrompt(request: string, fragments: PromptFragment[]): string {
  return `${fragmentsBlock(fragments)}

${requestBlock(request)}`;
}

export function specPrompt(
  request: string,
  fragments: PromptFragment[],
  analysis: { what: string; where: string; reasoning: string },
): string {
  return `${fragmentsBlock(fragments)}

${requestBlock(request)}

Разбор заявки:
- Чего хочет автор: ${analysis.what}
- Где в системе: ${analysis.where}
- Обоснование: ${analysis.reasoning}`;
}
